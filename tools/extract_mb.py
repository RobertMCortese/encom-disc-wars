#!/usr/bin/env python3
"""Cut the right-hemisphere mushroom body out of the FlyWire connectome and
write it to mbdata.js.

Inputs (both public):
  Connectivity_783.parquet  -- github.com/philshiu/Drosophila_brain_model
  Supplemental_file1_neuron_annotations.tsv
                            -- github.com/flyconnectome/flywire_annotations

  python3 tools/extract_mb.py Connectivity_783.parquet \
      Supplemental_file1_neuron_annotations.tsv mbdata.js
"""
import sys, json
import numpy as np
import pandas as pd

conn_path, ann_path, out_path = sys.argv[1:4]

a = pd.read_csv(ann_path, sep="\t", dtype=str)
a = a[a.side == "right"]
sel = a[a.cell_class.isin(["Kenyon_Cell", "MBON", "DAN", "ALPN"])].copy()
sel["grp"] = sel.cell_class
sel["rid"] = sel.root_id.astype("int64")

c = pd.read_parquet(conn_path)
ids = set(sel.rid)
e = c[c.Presynaptic_ID.isin(ids) & c.Postsynaptic_ID.isin(ids)]
g = dict(zip(sel.rid, sel.grp))
e = e.assign(pg=e.Presynaptic_ID.map(g), qg=e.Postsynaptic_ID.map(g))

groups = {"ALPN": "pn", "Kenyon_Cell": "kc", "MBON": "mbon", "DAN": "dan"}
out, idx = {}, {}
for grp, k in groups.items():
    s = sel[sel.grp == grp].sort_values("cell_type" if grp != "Kenyon_Cell" else "rid")
    s = s.reset_index(drop=True)
    idx[k] = {r: i for i, r in enumerate(s.rid)}
    out[k] = s

def xy(s):
    x = pd.to_numeric(s.soma_x, errors="coerce").fillna(pd.to_numeric(s.pos_x))
    y = pd.to_numeric(s.soma_y, errors="coerce").fillna(pd.to_numeric(s.pos_y))
    return x.values, y.values

X, Y = xy(pd.concat(out.values()))
x0, x1, y0, y1 = X.min(), X.max(), Y.min(), Y.max()

def q(s):
    x, y = xy(s)
    xs = [int(round((v - x0) / (x1 - x0) * 255)) for v in x]
    ys = [int(round((v - y0) / (y1 - y0) * 255)) for v in y]
    return [v for pair in zip(xs, ys) for v in pair]

def edges(src, dst, at_least):
    x = e[(e.pg == src) & (e.qg == dst) & (e.Connectivity >= at_least)]
    ia = x.Presynaptic_ID.map(idx[groups[src]])
    ib = x.Postsynaptic_ID.map(idx[groups[dst]])
    arr = np.stack([ia.values, ib.values, x.Connectivity.values], 1)
    arr = arr[np.lexsort((arr[:, 0], arr[:, 1]))]
    return arr.flatten().astype(int).tolist()

kc_types = sorted(set(out["kc"].cell_type))
data = {
    "source": "FlyWire FAFB v783 (Dorkenwald et al. 2024, Schlegel et al. 2024; "
              "connectivity table from Shiu et al. 2024). Right hemisphere mushroom body.",
    "pnGlom": [t.split("_")[0] for t in out["pn"].cell_type],
    "mbonType": out["mbon"].cell_type.tolist(),
    "mbonNt": out["mbon"].top_nt.tolist(),
    "danType": out["dan"].cell_type.tolist(),
    "kcType": [kc_types.index(t) for t in out["kc"].cell_type],
    "pnKc": edges("ALPN", "Kenyon_Cell", 3),
    "kcMbon": edges("Kenyon_Cell", "MBON", 3),
    "danMbon": edges("DAN", "MBON", 1),
    "danKc": edges("DAN", "Kenyon_Cell", 2),
    "kcTypes": kc_types,
}
for k in ["pn", "kc", "mbon", "dan"]:
    data[k + "XY"] = q(out[k])

with open(out_path, "w") as f:
    f.write("// The mushroom body of a real fruit fly, right hemisphere, out of the FlyWire\n"
            "// whole-brain connectome (FAFB v783). Generated by tools/extract_mb.py -- do\n"
            "// not edit by hand. Edges are flat [from, to, synapses] triples.\n"
            "window.FlyMB = " + json.dumps(data, separators=(",", ":")) + ";\n")
